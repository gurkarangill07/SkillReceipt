import assert from "node:assert/strict";
import { test } from "node:test";
import { CODING_EXAMPLE, CODING_STARTER } from "../../lib/coding";
import { CookieClient, expectError, monitoredSubmission } from "../helpers/http-client.mjs";
import type { SessionContext } from "../../lib/contracts";
import { startIsolatedApp } from "../helpers/next-server.mjs";

test("résumé to assessment to employer report works without accounts and respects publication control", { timeout: 180_000 }, async (t) => {
  const app = await startIsolatedApp();
  const candidate = new CookieClient(app.origin);
  const employer = new CookieClient(app.origin);
  const outsider = new CookieClient(app.origin);
  let candidateId = "", privateReceiptId = "", ownerCookie = "";
  let savedSession: SessionContext;
  const session = { mode: "practice", cameraStarted: false, tabSwitches: 1, interruptions: 0, activeSeconds: 42, focusLosses: 2, pasteEvents: 1, fullscreenExits: 0, fullscreenStarted: false };
  const engineer = { kind: "data-engineer-v2", answers: { key: "order_id", missing: "quarantine", load: "upsert" }, code: CODING_STARTER, session };
  try {
    await t.test("candidate creates a private browser profile and adds a parsed résumé", async () => {
      assert.equal((await employer.request("/employer")).status, 200);
      assert.deepEqual(await (await candidate.request("/api/candidate")).json(), { candidate: null });
      const create = await candidate.json("/api/candidate", { name: "Taylor WorkSample" });
      assert.equal(create.status, 200);
      assert.ok(create.headers.getSetCookie().some((cookie: string) => /HttpOnly/i.test(cookie) && /SameSite=lax/i.test(cookie)));
      const profile = (await create.json()).candidate;
      candidateId = profile.id;
      assert.match(candidateId, /^SR-[A-F0-9]{10}$/);
      assert.equal(profile.visible, false);
      ownerCookie = candidate.cookieHeader.split("=").slice(1).join("=");
      const uploaded = await candidate.request("/api/resume", { method: "POST", headers: { "X-Resume-Name": "taylor-resume.txt", "Content-Type": "text/plain" }, body: "Taylor WorkSample\nPRIVATE_EMAIL taylor@example.invalid\nSQL Python ETL" });
      assert.equal(uploaded.status, 200);
      const resume = await uploaded.json();
      assert.ok(resume.skills.includes("SQL") && resume.skills.includes("Python"));
      assert.ok(!JSON.stringify(resume).includes("PRIVATE_EMAIL"));
      const saved = await candidate.json("/api/candidate", { resume: { ...resume, skills: [...resume.skills, "UnassessedRareTool"] } });
      assert.equal(saved.status, 200);
      assert.equal((await saved.json()).candidate.id, candidateId);
      await expectError(await candidate.json("/api/candidate", { visible: true }), 400);
      await expectError(await employer.request(`/api/employer/candidates/${candidateId}`), 404);
      assert.deepEqual(await (await employer.request("/api/employer/search")).json(), { candidates: [] });
    });
    await t.test("assessment is graded on the server, retains session observations, and remains private before publishing", async () => {
      const submitted = await candidate.json("/api/receipts", await monitoredSubmission(candidate, { demo: false, session, workSample: engineer, score: 100 }, ["tab_hidden", "focus_lost", "paste_blocked"]));
      assert.equal(submitted.status, 201);
      const receipt = await submitted.json();
      privateReceiptId = receipt.id;
      assert.equal(receipt.evaluation.score, 80);
      savedSession = receipt.submission.session;
      assert.equal(savedSession.mode, "camera");
      assert.equal(savedSession.tabSwitches, 1);
      assert.equal(savedSession.pasteEvents, 1);
      assert.ok(savedSession.integrity!.events.some((event) => event.kind === "tab_hidden"));
      assert.equal(receipt.submission.demo, false);
      await expectError(await outsider.request(`/api/receipts/${privateReceiptId}`), 404);
      await expectError(await employer.request(`/api/employer/candidates/${candidateId}`), 404);
    });
    await t.test("opt-in exposes actual assessed skills and a safe detailed report without a second login", async () => {
      const publish = await candidate.json("/api/candidate", { visible: true });
      assert.equal(publish.status, 200);
      const results = await (await employer.request("/api/employer/search?q=JavaScript&minScore=80&includeExamples=false")).json();
      assert.equal(results.candidates.length, 1);
      const match = results.candidates[0];
      assert.equal(match.candidate.id, candidateId);
      assert.equal(match.topScore, 80);
      assert.equal(match.examplesOnly, false);
      assert.ok(match.testedSkills.includes("JavaScript"));
      assert.equal((await (await employer.request("/api/employer/search?q=UnassessedRareTool")).json()).candidates.length, 0);
      assert.equal((await (await employer.request("/api/employer/search?q=JavaScript&minScore=90&includeExamples=false")).json()).candidates.length, 0);
      const reportResponse = await employer.request(`/api/employer/candidates/${candidateId}`);
      assert.equal(reportResponse.status, 200);
      const report = await reportResponse.json();
      assert.equal(report.candidate.name, "Taylor WorkSample");
      assert.equal(report.candidate.resume.name, "taylor-resume.txt");
      assert.equal(report.reports.length, 1);
      assert.equal(report.reports[0].evaluation.score, 80);
      assert.equal(report.reports[0].submission.workSample.code, CODING_STARTER);
      assert.deepEqual(report.reports[0].submission.session, savedSession);
      const serialized = JSON.stringify(report);
      for (const secret of [privateReceiptId, ownerCookie, "ownerHash", "shareToken", "PRIVATE_EMAIL", "passwordHash"]) assert.ok(!serialized.includes(secret), secret);
      assert.equal((await employer.request(`/employer?candidate=${candidateId}`)).status, 200);
    });
    await t.test("worked examples remain labeled and can be excluded from employer skill searches", async () => {
      const presentation = { ...session, mode: "presentation", tabSwitches: 0, focusLosses: 0, pasteEvents: 0, activeSeconds: 0 };
      const submitted = await candidate.json("/api/receipts", { demo: false, session: presentation, workSample: { ...engineer, code: CODING_EXAMPLE, session: presentation } });
      assert.equal(submitted.status, 201);
      const receipt = await submitted.json();
      assert.equal(receipt.submission.demo, true);
      assert.equal(receipt.evaluation.score, 100);
      const included = await (await employer.request("/api/employer/search?q=JavaScript&minScore=90&includeExamples=true")).json();
      assert.equal(included.candidates.length, 1);
      assert.equal(included.candidates[0].topScore, 100);
      const excluded = await (await employer.request("/api/employer/search?q=JavaScript&minScore=90&includeExamples=false")).json();
      assert.equal(excluded.candidates.length, 0);
      const report = await (await employer.request(`/api/employer/candidates/${candidateId}`)).json();
      assert.equal(report.reports.length, 2);
      assert.deepEqual(report.reports.map((item: { submission: { demo: boolean } }) => item.submission.demo).sort(), [false, true]);
    });
    await t.test("other browser profiles and cross-origin requests cannot change the candidate", async () => {
      const created = await outsider.json("/api/candidate", { name: "Different Candidate", id: candidateId });
      assert.equal(created.status, 200);
      const ownId = (await created.json()).candidate.id;
      assert.notEqual(ownId, candidateId);
      const changed = await outsider.json("/api/candidate", { name: "Other Updated", id: candidateId, visible: false });
      assert.equal(changed.status, 200);
      assert.equal((await changed.json()).candidate.id, ownId);
      await expectError(await candidate.json("/api/candidate", { visible: false }, { Origin: "https://unrelated.invalid" }), 400);
      assert.equal((await (await candidate.request("/api/candidate")).json()).candidate.name, "Taylor WorkSample");
      assert.equal((await employer.request(`/api/employer/candidates/${candidateId}`)).status, 200);
    });
    await t.test("revoking employer access blocks fresh searches/reports while preserving private results", async () => {
      assert.equal((await candidate.json("/api/candidate", { visible: false })).status, 200);
      await expectError(await employer.request(`/api/employer/candidates/${candidateId}`), 404);
      assert.equal((await (await employer.request(`/api/employer/search?q=${candidateId}`)).json()).candidates.length, 0);
      assert.equal((await candidate.request(`/api/receipts/${privateReceiptId}`)).status, 200);
      await app.restart();
      const profile = (await (await candidate.request("/api/candidate")).json()).candidate;
      assert.equal(profile.id, candidateId);
      assert.equal(profile.visible, false);
      await expectError(await employer.request(`/api/employer/candidates/${candidateId}`), 404);
    });
  } finally { await app.close(); }
});
