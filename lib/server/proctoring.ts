import "server-only";
import { randomUUID } from "node:crypto";
import path from "node:path";
import { FileJsonDocuments, cloudStorageEnabled, newCloudDocuments, type JsonDocuments } from "./documents";
import { validId } from "./store";
import { InputError } from "../validation";
import { stateReady } from "../proctor-validation";
import { MAX_EVENTS, MAX_SESSION_MS, PROCTOR_POLICY, STALE_AFTER_MS, type ClientIntegrityEvent, type IntegrityAudit, type IntegrityEvent, type ProctorState } from "../proctoring";
import type { SessionContext } from "../contracts";

type Record = { id: string; owner: string; exercise: string; startedAt: string; lastSeen: number; lastSeq: number; heartbeats: number; connectionGaps: number; events: IntegrityEvent[]; state: ProctorState; sealed?: SessionContext };
export class ProctorRepository {
  constructor(readonly documents: JsonDocuments, private readonly now = () => Date.now()) {}
  async start(owner: string, exercise: string, state: ProctorState) {
    if (!stateReady(state)) throw new InputError("Camera, one visible face and fullscreen are required to start.");
    const time = this.now(), id = randomUUID();
    const record: Record = { id, owner, exercise, startedAt: new Date(time).toISOString(), lastSeen: time, lastSeq: 0, heartbeats: 1, connectionGaps: 0, state, events: [{ seq: 0, kind: "session_started", elapsedMs: 0, receivedAt: new Date(time).toISOString() }] };
    if (!await this.documents.compareAndSet(`${id}.json`, record, null)) throw new Error("Session could not start.");
    return { id, startedAt: record.startedAt, lastSeq: 0 };
  }
  private async update<T>(id: string, owner: string, operation: (record: Record, now: number) => T) {
    if (!validId(id)) throw new InputError("Start a monitored assessment first.");
    for (let retry = 0; retry < 8; retry++) {
      const current = await this.documents.read(`${id}.json`);
      const record = current?.value as Record | undefined;
      if (!record || record.owner !== owner) throw new InputError("Assessment session unavailable. Start a new assessment in this browser.");
      if (this.now() - Date.parse(record.startedAt) > MAX_SESSION_MS) throw new InputError("This assessment session expired. Start a new attempt.");
      const result = operation(record, this.now());
      if (await this.documents.compareAndSet(`${id}.json`, record, current!.version)) return result;
    }
    throw new InputError("Session changed in another request. Retry the check-in.");
  }
  async append(id: string, owner: string, events: ClientIntegrityEvent[], state: ProctorState) {
    return this.update(id, owner, (record, now) => {
      if (record.sealed) throw new InputError("This assessment was already submitted.");
      const receivedAt = new Date(now).toISOString();
      if (now - record.lastSeen > STALE_AFTER_MS) {
        record.connectionGaps++;
        record.events.push({ seq: 0, kind: "connection_gap", elapsedMs: now - Date.parse(record.startedAt), receivedAt });
      }
      for (const event of events) {
        if (["session_started", "session_submitted", "connection_gap", "heartbeat"].includes(event.kind)) throw new InputError("This event is generated by the server.");
        if (event.seq <= record.lastSeq) {
          const previous = record.events.find((item) => item.seq === event.seq);
          if (!previous || previous.kind !== event.kind || previous.elapsedMs !== event.elapsedMs) throw new InputError("Session event history cannot be replaced.");
          continue; // An acknowledged event may be retried after a lost response.
        }
        if (event.seq !== record.lastSeq + 1 || event.elapsedMs < ([...record.events].reverse().find((item) => item.seq > 0)?.elapsedMs ?? 0) || event.elapsedMs > now - Date.parse(record.startedAt) + 5000) throw new InputError("Session event sequence or timing is invalid.");
        if (record.lastSeq >= MAX_EVENTS) throw new InputError("Session event limit reached. Submit or start a new attempt.");
        record.events.push({ ...event, receivedAt }); record.lastSeq = event.seq;
      }
      record.heartbeats++; record.lastSeen = now; record.state = state;
      return { lastSeq: record.lastSeq, receivedAt };
    });
  }
  async seal(id: string, owner: string, exercise: string, lastSeq: number): Promise<SessionContext> {
    return this.update(id, owner, (record, now) => {
      if (record.exercise !== exercise) throw new InputError("This session belongs to a different exercise.");
      if (record.sealed) return record.sealed;
      if (record.lastSeq !== lastSeq) throw new InputError("Wait for all session events to sync before submitting.");
      if (now - record.lastSeen > STALE_AFTER_MS || !stateReady(record.state)) throw new InputError("Restore your camera, face check, fullscreen and session connection before submitting.");
      const count = (...kinds: string[]) => record.events.filter((event) => kinds.includes(event.kind)).length;
      const integrity: IntegrityAudit = { policy: PROCTOR_POLICY, startedAt: record.startedAt, endedAt: new Date(now).toISOString(), heartbeats: record.heartbeats, connectionGaps: record.connectionGaps, events: [...record.events, { seq: 0, kind: "session_submitted", elapsedMs: now - Date.parse(record.startedAt), receivedAt: new Date(now).toISOString() }] };
      const elapsed = (now - Date.parse(record.startedAt)) / 1000;
      // Active time is deliberately not inferred from client counters.
      record.sealed = { mode: "camera", cameraStarted: true, fullscreenStarted: true, sessionId: id, tabSwitches: count("tab_hidden"), focusLosses: count("focus_lost"), interruptions: count("camera_interrupted", "camera_obscured", "camera_stalled"), pasteEvents: count("paste_blocked"), fullscreenExits: count("fullscreen_exit"), activeSeconds: Math.floor(elapsed), integrity };
      return record.sealed;
    });
  }
}
export function getProctorRepository() {
  const directory = path.resolve(/*turbopackIgnore: true*/ process.env.SKILLRECEIPT_DATA_DIR ?? path.join(process.cwd(), ".data"));
  return new ProctorRepository(cloudStorageEnabled() ? newCloudDocuments("proctoring") : new FileJsonDocuments(path.join(directory, "proctoring")));
}
